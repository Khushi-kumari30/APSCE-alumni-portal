// UPGRADED REGISTER ROUTE: Auto-generates a secure JWT token upon registration success
app.post('/api/verify-and-register', async (req, res) => {
    const { firstName, lastName, email, password, role, otp, usn } = req.body;

    // Server-side block: verify that the USN exists and starts with '1AP'
    if (!usn || !usn.trim().toUpperCase().startsWith('1AP')) {
        return res.status(403).json({ message: "Access Denied: Registration is restricted to 1AP college credentials only." });
    }

    try {
        const [rows] = await db.query(
            'SELECT * FROM otp_verification WHERE email = ? AND otp_code = ? AND expires_at > NOW()',
            [email, otp]
        );

        if (rows.length === 0) return res.status(400).json({ message: "Invalid or expired OTP" });

        const salt = await bcrypt.genSalt(10);
        const hashedPassword = await bcrypt.hash(password, salt);

        // 1. Insert Core Profile info into the 'users' table
        const sqlUser = `INSERT INTO users (first_name, last_name, email, password_hash, role, is_verified) VALUES (?, ?, ?, ?, ?, TRUE)`;
        const [userResult] = await db.query(sqlUser, [firstName, lastName, email, hashedPassword, role]);
        
        // Extract the auto-incremented user_id generated by MySQL
        const newUserId = userResult.insertId;

        // 2. Insert USN & relational defaults into the 'alumni_profiles' table 
        const defaultBranch = "Not Specified";
        const defaultYear = new Date().getFullYear();

        const sqlProfile = `INSERT INTO alumni_profiles (user_id, usn, branch, passing_year) VALUES (?, ?, ?, ?)`;
        await db.query(sqlProfile, [newUserId, usn.trim().toUpperCase(), defaultBranch, defaultYear]);

        // 3. Clean up active verification OTP logs
        await db.query('DELETE FROM otp_verification WHERE email = ?', [email]);

        // === AUTO-LOGIN GATEWAY INTEGRATION ===
        // Generate a valid access token immediately so register.html can jump straight to index3.html
        const token = jwt.sign({ id: newUserId, role: role }, JWT_SECRET, { expiresIn: '7d' });

        res.status(201).json({ 
            message: "Registered successfully!",
            token,
            user: { id: newUserId, name: firstName, role: role }
        });
    } catch (err) {
        console.error("Registration Error:", err);
        res.status(500).json({ message: "Registration failed", error: err.message });
    }
});

app.post('/api/login', async (req, res) => {
    const { email, password } = req.body;
    try {
        const [rows] = await db.query('SELECT * FROM users WHERE email = ?', [email]);
        if (rows.length === 0) return res.status(404).json({ error: "User not found" });

        const user = rows[0];
        const isMatch = await bcrypt.compare(password, user.password_hash);
        if (!isMatch) return res.status(400).json({ error: "Invalid credentials" });

        const token = jwt.sign({ id: user.user_id, role: user.role }, JWT_SECRET, { expiresIn: '7d' });
        res.json({ 
            token, 
            user: { id: user.user_id, name: user.first_name, role: user.role } 
        });
    } catch (err) {
        res.status(500).json({ error: "Server error" });
    }
});

